package webrtc.report

/** Stable check identifiers shared by the concise checklist and detailed evidence rows. */
enum class CoverageGroup(val title: String) {
    AUTHENTICATION("Authentication"), MEDIA("Media and RTP security tests"),
    RESILIENCE("Resilience testing"), SIGNALING("Signaling protocol-specific tests"),
    OTHER("Other security categories")
}

enum class CoverageSupport(val label: String) {
    BUILT_IN("Built in"), PARTIAL("Partial coverage"), EXTERNAL("External / manual")
}

enum class CoverageCheck(
    val title: String, val area: SecurityArea, val support: CoverageSupport,
    val scope: String, val nextStep: String, vararg val groups: CoverageGroup
) {
    SIGNALING_AUTH("Signaling authentication tests", SecurityArea.AUTH, CoverageSupport.PARTIAL,
        "M5 compares selected HTTP requests across identities and with known auth headers removed; response codes are review leads.",
        "Run M5 on a signaling request; verify protected content and remove any application tokens in its URL/body separately.", CoverageGroup.AUTHENTICATION),
    WEBSOCKET_AUTH("WebSocket authentication tests", SecurityArea.SIGNALING, CoverageSupport.EXTERNAL,
        "No automated WebSocket handshake or message authentication tests.",
        "Use Burp WebSocket testing to compare absent/invalid credentials, Origin, per-message authorization, logout and reconnect behavior.", CoverageGroup.AUTHENTICATION),
    TURN_AUTH("TURN server authentication tests", SecurityArea.NAT, CoverageSupport.PARTIAL,
        "M6 observes allocations with supplied credentials; it does not automatically compare valid, missing, invalid or expired credentials.",
        "Repeat M6 with each credential condition and compare relay allocation; a failed gather alone does not prove authentication enforcement.", CoverageGroup.AUTHENTICATION),
    SRTP_AUTH("SRTP authentication tests", SecurityArea.MEDIA, CoverageSupport.EXTERNAL,
        "Cipher observations do not test authentication-tag rejection or replay protection.",
        "Use a controlled packet harness with test keys to alter tags, replay packets and verify receiver rejection counters.", CoverageGroup.AUTHENTICATION),
    TLS_VERSION("TLS version security checks", SecurityArea.SIGNALING, CoverageSupport.BUILT_IN,
        "TLS Tests probes SSL/TLS versions on a selected TCP listener; media DTLS is separate.",
        "Run TLS Tests on the relevant HTTPS/WSS or TURN-over-TLS listener.", CoverageGroup.AUTHENTICATION),
    TLS_CIPHER("Cipher-Suite security analysis", SecurityArea.SIGNALING, CoverageSupport.BUILT_IN,
        "TLS Tests enumerates TCP listener cipher suites; DTLS and SRTP negotiated profiles are listed separately.",
        "Run TLS Tests and inspect per-protocol cipher results.", CoverageGroup.AUTHENTICATION),
    TURN_ABUSE("TURN relay abuse tests", SecurityArea.NAT, CoverageSupport.PARTIAL,
        "M6 allocation is a precondition only; it does not test destination restrictions or forwarding.",
        "Use External Tests: stunner, TURNado or TURNt with an authorized destination and verify actual transfer.", CoverageGroup.MEDIA),
    DTLS_CERT("DTLS certificate analysis", SecurityArea.DTLS, CoverageSupport.BUILT_IN,
        "Captured X.509 validity, key strength and SDP fingerprint binding; remote enforcement is not tested.",
        "Join a call and Capture stats (T1) to collect certificates and matching SDP.", CoverageGroup.MEDIA),
    DTLS_CIPHER("DTLS Crypto-Suite analysis", SecurityArea.DTLS, CoverageSupport.PARTIAL,
        "Reviews the browser's negotiated cipher/version; does not enumerate every supported DTLS suite or attempt downgrade attacks.",
        "Capture stats (T1); use a DTLS peer harness for active suite/downgrade testing.", CoverageGroup.MEDIA),
    SRTP_SECURITY("SRTP security tests", SecurityArea.MEDIA, CoverageSupport.PARTIAL,
        "Reviews negotiated SRTP profiles and SDP keying; packet integrity, SRTCP and key lifecycle need external tests.",
        "Collect media-call telemetry and use a packet harness for tag, replay and rekey tests.", CoverageGroup.MEDIA),
    RTP_INJECTION("RTP injection", SecurityArea.MEDIA, CoverageSupport.EXTERNAL,
        "The extension does not transmit crafted RTP/RTCP packets.",
        "Use a controlled media peer/packet harness and verify receiver acceptance; do not treat SDP port 9 or ICE candidates as plaintext RTP targets.", CoverageGroup.MEDIA),
    RTP_BLEED("RTP bleed", SecurityArea.MEDIA, CoverageSupport.EXTERNAL,
        "No RTP Bleed test executes inside the extension.",
        "Use External Tests: SIPPTS rtpbleed with a confirmed media endpoint/port range; retain returned-packet evidence.", CoverageGroup.MEDIA),
    RTP_FLOOD("RTP flooding", SecurityArea.DOS, CoverageSupport.EXTERNAL,
        "Local negotiation and DataChannel tests do not flood RTP.",
        "Use a bounded media load harness with an agreed rate/duration and record service health, loss and recovery.", CoverageGroup.MEDIA),
    RTP_FUZZ("RTP packet fuzzing", SecurityArea.MEDIA, CoverageSupport.EXTERNAL,
        "No RTP/RTCP packet mutation or native media-parser fuzzing.",
        "Use a packet/native fuzz harness against a controlled receiver; preserve seeds, crash traces and reproduction steps.", CoverageGroup.MEDIA, CoverageGroup.RESILIENCE),
    CODEC_FUZZ("Codec fuzzing", SecurityArea.SDP, CoverageSupport.PARTIAL,
        "M3+ mutates codec SDP parameters in the local browser parser; encoded frames and native decoders are not fuzzed.",
        "Run M3+ with codec cases; use a separate decoder harness for encoded-media fuzzing.", CoverageGroup.MEDIA, CoverageGroup.RESILIENCE),
    CODEC_ENUM("Codec enumeration", SecurityArea.SDP, CoverageSupport.BUILT_IN,
        "Enumerates advertised SDP codecs and captured in-use RTP codecs; advertisement does not prove negotiation.",
        "Join a media call to capture SDP and RTP stats.", CoverageGroup.MEDIA),
    SIGNALING_FUZZ("Signalling black box fuzzing", SecurityArea.SIGNALING, CoverageSupport.PARTIAL,
        "M3/M3+ cover SDP mutation/local parsing only; no server signaling black-box fuzzer.",
        "Use Burp Repeater/Intruder or WebSocket testing for application message schemas, malformed fields and server responses.", CoverageGroup.RESILIENCE),
    SIGNALING_DOS("Signaling denial of service testing", SecurityArea.DOS, CoverageSupport.PARTIAL,
        "T8 runs bounded local offer/ICE-restart operations; it sends no signaling flood to the server.",
        "Use a bounded signaling load harness and measure server availability and recovery separately.", CoverageGroup.RESILIENCE),
    API_FLOOD("API flooding", SecurityArea.DOS, CoverageSupport.EXTERNAL,
        "No HTTP/API rate-limit or saturation test is implemented; M5 replays are not a load test.",
        "Use an application load harness with a fixed request/concurrency budget and inspect throttling, quotas and recovery.", CoverageGroup.RESILIENCE),
    SIP_WS("SIP security tests over WebSocket", SecurityArea.SIGNALING, CoverageSupport.EXTERNAL,
        "Requires confirmed SIP-over-WS/WSS use; SDP alone does not establish SIP. No automatic SIP test executes.",
        "Use External Tests: sipexer with the exact WS/WSS path and test accounts; verify registration, dialog and authorization behavior.", CoverageGroup.SIGNALING),
    INJECTION("Injection security tests", SecurityArea.SDP, CoverageSupport.PARTIAL,
        "M3 changes SDP and M3+ tests local parsing; server-side SQL/command/template and application message injection need dedicated cases.",
        "Run M3/M3+ and test captured signaling inputs in Burp, correlating responses and application effects.", CoverageGroup.SIGNALING),
    API_SECURITY("API security tests where applicable", SecurityArea.AUTH, CoverageSupport.PARTIAL,
        "M5 provides HTTP identity/identifier replay; schema validation, business logic, CSRF and endpoint-specific controls remain manual.",
        "Run M5 on protected API requests and verify resource ownership and intended permissions.", CoverageGroup.SIGNALING),
    TRANSPORT("Signaling transport / HSTS", SecurityArea.SIGNALING, CoverageSupport.PARTIAL,
        "Reviews captured HTTP origins and HSTS; does not establish application signaling identity.",
        "Capture in-scope requests and review original response policies.", CoverageGroup.OTHER),
    ICE_PRIVACY("ICE / IP-location privacy", SecurityArea.ICE, CoverageSupport.PARTIAL,
        "Reviews application candidates and exposed addresses; absent observations do not prove relay-only privacy.",
        "Capture a call under the intended ICE policy and review candidate exposure.", CoverageGroup.OTHER),
    ICE_CREDS("ICE credential hygiene", SecurityArea.ICE, CoverageSupport.PARTIAL,
        "Reviews captured credential length/diversity; TURN account credentials are separate.",
        "Capture SDP and compare credential changes during deliberate ICE restarts.", CoverageGroup.OTHER),
    DATA_CHANNEL("DataChannel / SCTP security", SecurityArea.DATA, CoverageSupport.PARTIAL,
        "M4 records lifecycle and bounded payload sends; native SCTP and remote message authorization remain separate.",
        "Run M4 on an open channel and verify remote handling.", CoverageGroup.OTHER),
    SESSION("Session / token / room access", SecurityArea.AUTH, CoverageSupport.EXTERNAL,
        "HTTP response codes do not establish expiry, revocation, logout or room membership enforcement.",
        "Test session lifecycle and room/media access using separate principals and expired/revoked tokens.", CoverageGroup.OTHER),
    PERMISSIONS("Browser media permissions", SecurityArea.CLIENT, CoverageSupport.PARTIAL,
        "Observes camera/microphone outcomes without media contents; does not attempt a permission bypass.",
        "Exercise permission grant, denial and revocation in the browser.", CoverageGroup.OTHER),
    BROWSER_ORIGIN("Browser XSS / origin / iframe policy", SecurityArea.CLIENT, CoverageSupport.EXTERNAL,
        "Instrumentation and CSP stripping are not enforcement tests.",
        "Test original responses and browser behavior for XSS, Origin, frame and Permissions Policy controls.", CoverageGroup.OTHER),
    ARCHITECTURE("SFU / MCU / gateway isolation", SecurityArea.ARCHITECTURE, CoverageSupport.EXTERNAL,
        "Topology, tenant isolation and gateway trust cannot be established from endpoint names.",
        "Review architecture and test cross-tenant routing, transcoding and media access.", CoverageGroup.OTHER),
    STORAGE("Recording / storage / compliance", SecurityArea.STORAGE, CoverageSupport.EXTERNAL,
        "No archival or compliance assessment is automated.",
        "Review recording access, consent, retention/deletion, encryption at rest and applicable policy evidence.", CoverageGroup.OTHER),
    E2EE("End-to-end media encryption", SecurityArea.MEDIA, CoverageSupport.EXTERNAL,
        "DTLS-SRTP transport encryption alone does not establish end-to-end encryption through an SFU/MCU.",
        "Verify media key ownership, intermediary access and participant/key lifecycle against the application design.", CoverageGroup.OTHER)
}
